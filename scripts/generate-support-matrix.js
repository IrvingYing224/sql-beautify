var fs = require('fs');
var path = require('path');
var clauseRegistry = require('../lib/core/sql-clause-registry');
var operatorRegistry = require('../lib/core/sql-operator-registry');
var sqlDialect = require('../lib/core/sql-dialect');

var DIALECTS = ['generic', 'hive', 'postgres', 'mysql'];
var outputPath = path.join(__dirname, '..', 'docs', 'technical', 'sql-support-matrix.md');

function dialect_list(values) {
    return values.join(', ');
}

function yes_no(value) {
    return value ? 'yes' : 'no';
}

function render_clause_table() {
    var lines = [
        '| Clause | Dialects | Select start | Select end | Condition clause | Statement start |',
        '| --- | --- | --- | --- | --- | --- |'
    ];

    clauseRegistry.CLAUSES.forEach(function(clause) {
        lines.push([
            '| ' + clause.name,
            dialect_list(clause.dialects),
            yes_no(clause.selectStart),
            yes_no(clause.selectEnd),
            yes_no(clause.conditionClause),
            yes_no(clause.statementStart) + ' |'
        ].join(' | '));
    });

    return lines.join('\n');
}

function render_operator_table() {
    var lines = [
        '| Operator | Dialects | Spacing |',
        '| --- | --- | --- |'
    ];

    operatorRegistry.OPERATORS.forEach(function(operator) {
        lines.push('| `' + operator.value + '` | ' + dialect_list(operator.dialects) + ' | ' + operator.spacing + ' |');
    });

    return lines.join('\n');
}

function render_dialect_table() {
    var lines = [
        '| Dialect | Dollar quoted strings | Hash line comments | PostgreSQL JSON operators | Clauses | Operators |',
        '| --- | --- | --- | --- | --- | --- |'
    ];

    DIALECTS.forEach(function(dialect) {
        var capabilities = sqlDialect.get_capabilities(dialect);
        lines.push([
            '| ' + dialect,
            yes_no(capabilities.dollarQuotedStrings),
            yes_no(capabilities.hashLineComments),
            yes_no(capabilities.postgresJsonOperators),
            String(capabilities.clauseRegistry.length),
            String(Object.keys(capabilities.operatorLookup).length) + ' |'
        ].join(' | '));
    });

    return lines.join('\n');
}

function render_matrix() {
    return [
        '# SQL Formatter Support Matrix',
        '',
        '<!-- Generated by scripts/generate-support-matrix.js. Do not edit this file by hand. -->',
        '',
        'This matrix is generated from the formatter registries. It describes the maintained formatting boundary, not a complete SQL parser contract.',
        '',
        '## Dialects',
        '',
        render_dialect_table(),
        '',
        '## Clauses',
        '',
        render_clause_table(),
        '',
        '## Operators',
        '',
        render_operator_table(),
        '',
        '## Experimental Hive DDL',
        '',
        'Hive DDL formatting and Extract DDL live under `lib/experimental/ddl/`.',
        '',
        '- Scope: covered Hive-style DDL formatting and top-level SELECT-field extraction only',
        '- Non-goal: a general DDL parser or real type inference engine',
        '- Operational expectation: output may be useful as a draft, but complex DDL and extracted schemas still require human review',
        '',
        '## Unsupported Policy',
        '',
        'Unsupported or dialect-specific syntax should be preserved when confidence is low. Core formatting must prefer opaque protection over speculative rewrites.',
        '',
        '- `preserve`: continue formatting around preserved unsupported fragments',
        '- `warn`: same preservation behavior, plus runtime warning diagnostics in the adapter layer',
        '- `bail_out`: reject formatting when protected unsupported fragments are detected',
        '',
        '## Diagnostics',
        '',
        '- Unsafe range fragments are rejected instead of being partially reformatted',
        '- Runtime warnings are intended for low-confidence-but-preserved cases such as protected unsupported syntax',
        ''
    ].join('\n');
}

var matrix = render_matrix();

if (process.argv.indexOf('--write') >= 0) {
    fs.writeFileSync(outputPath, matrix, 'utf8');
} else {
    process.stdout.write(matrix);
}
