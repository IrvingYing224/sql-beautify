'use strict';

var fs = require('fs');
var path = require('path');
var registryModule = require('../.tmp/v2-core/core/dialects/registry.js');

var outputPath = path.join(
    __dirname,
    '..',
    'docs',
    'technical',
    'sql-formatter-v2-support-matrix.md'
);

function collectFacts() {
    var registry = registryModule.getDialectCapabilityRegistry();
    var dialects = registry.listDialects().slice().sort();
    var capabilityIds = new Set();
    var states = new Map();

    dialects.forEach(function(dialect) {
        registry.getDialect(dialect).listCapabilities().forEach(function(capability) {
            capabilityIds.add(capability.id);
            states.set(dialect + '\0' + capability.id, capability.state);
        });
    });

    return {
        dialects: dialects,
        capabilityIds: Array.from(capabilityIds).sort(),
        states: states
    };
}

function renderMatrix() {
    var facts = collectFacts();
    var lines = [
        '# SQL Formatter V2 Support Matrix',
        '',
        '<!-- Generated by scripts/generate-v2-support-matrix.js. Do not edit by hand. -->',
        '',
        'This development-stage matrix records the current v2 capability states from the compiled dialect registry.',
        '',
        'It is independent from the maintained 1.x formatter support matrix. `—` means that the registry does not declare that capability for the dialect.',
        '',
        '| Capability | ' + facts.dialects.map(function(dialect) {
            return '`' + dialect + '`';
        }).join(' | ') + ' |',
        '| ' + new Array(facts.dialects.length + 1).fill('---').join(' | ') + ' |'
    ];

    facts.capabilityIds.forEach(function(capabilityId) {
        var row = facts.dialects.map(function(dialect) {
            var state = facts.states.get(dialect + '\0' + capabilityId);
            return state === undefined ? '—' : '`' + state + '`';
        });
        lines.push('| `' + capabilityId + '` | ' + row.join(' | ') + ' |');
    });
    lines.push('');
    return lines.join('\n');
}

function checkMatrix() {
    var expected = Buffer.from(renderMatrix(), 'utf8');
    var actual;
    try {
        actual = fs.readFileSync(outputPath);
    } catch (error) {
        if (error && error.code === 'ENOENT') {
            throw new Error(
                'Generated v2 support matrix is missing; run ' +
                    'node scripts/generate-v2-support-matrix.js --write'
            );
        }
        throw error;
    }
    if (!actual.equals(expected)) {
        throw new Error(
            'Generated v2 support matrix is stale; run ' +
                'node scripts/generate-v2-support-matrix.js --write'
        );
    }
}

function writeMatrix() {
    fs.writeFileSync(outputPath, renderMatrix(), 'utf8');
}

function run(args) {
    var mode;
    if (args.length === 0) {
        mode = '--check';
    } else if (args.length === 1 && (args[0] === '--check' || args[0] === '--write')) {
        mode = args[0];
    } else {
        throw new Error('Unknown argument: ' + args.join(' '));
    }

    if (mode === '--write') {
        writeMatrix();
        return;
    }
    checkMatrix();
}

if (require.main === module) {
    try {
        run(process.argv.slice(2));
    } catch (error) {
        process.stderr.write(String(error && error.message ? error.message : error) + '\n');
        process.exitCode = 1;
    }
}

module.exports = Object.freeze({
    renderMatrix: renderMatrix
});
